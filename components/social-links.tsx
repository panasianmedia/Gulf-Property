const icons: Record<SocialPlatform, (props: SVGProps<SVGSVGElement>) => ReactElement> = {
  instagram: InstagramIcon,
  facebook: FacebookIcon,
  linkedin: LinkedinIcon,
}

export function SocialLinks({
  className = "",
  variant = "default",
}: {
  className?: string
  /** "default" for light surfaces, "inverted" for dark surfaces (footer/top bar). */
  variant?: "default" | "inverted"
}) {
  const base =
    variant === "inverted"
      ? "border-white/20 text-gray-300 hover:border-realty hover:text-white"
      : "border-border text-muted-foreground hover:border-realty hover:text-realty"

  return (
    <div className={`flex items-center gap-2 ${className}`}>
      {socialLinks.map(({ label, href, platform }) => {
        const Icon = icons[platform]
        return (
          <a
            key={label}
            href={href}
            target="_blank"
            rel="noopener noreferrer"
            aria-label={label}
            title={label}
            className={`inline-flex h-8 w-8 items-center justify-center rounded-full border transition-colors ${base}`}
          >
            <Icon className="h-4 w-4" />
          </a>
        )
      })}
    </div>
  )
}
